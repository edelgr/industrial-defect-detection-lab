"""SYNTHETIC educational/development dataset.

!!! This is NOT a research dataset and NOT real industrial data. !!!

It procedurally renders brushed-metal-like textures with drawn scratches, dents and stains, and
small synthetic 3D surface patches with bumps/dents.  It exists so that the application, tests and
classroom demos have a deterministic fallback when no licensed dataset is installed.  Every result
computed on it is labelled "synthetic demonstration" in the experiment store and in the UI.
"""

from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np

from core.datasets.base import DatasetIndex, Sample, GOOD, BAD
from core.datasets.io import write_image
from core.datasets.mvtec import MVTecStyleAdapter

SYNTHETIC_ID = "SYN"
LABEL = "Synthetic Educational Data — Not a Real Industrial Benchmark"
NOTICE = (LABEL + ". Procedurally generated by IDD Lab (fixed seed); not real industrial imagery. "
          "Results on it are illustrative only.")
# Order matters: kinds are rendered in this order from one seeded generator, so appending new kinds
# keeps the images of the earlier kinds identical for the same seed.
DEFECT_KINDS = ("scratch", "dent", "stain", "spot", "geometric", "texture")


def _texture(rng: np.random.Generator, size: int) -> np.ndarray:
    base = rng.normal(0.0, 1.0, (size, size)).astype(np.float32)
    k = int(size * 0.12) | 1
    brushed = cv2.GaussianBlur(base, (k, 1), 0)            # directional "brushing"
    brushed = cv2.GaussianBlur(brushed, (1, 3), 0)
    brushed = (brushed - brushed.mean()) / (brushed.std() + 1e-6)
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32) / size
    angle = rng.uniform(0, 2 * np.pi)
    illum = 0.5 * (np.cos(angle) * xx + np.sin(angle) * yy)  # smooth illumination gradient
    img = 0.55 + 0.06 * brushed + 0.12 * (illum - illum.mean()) * rng.uniform(0.5, 1.5)
    return img


def _defect(rng: np.random.Generator, img: np.ndarray, kind: str) -> tuple[np.ndarray, np.ndarray]:
    s = img.shape[0]
    mask = np.zeros_like(img, dtype=np.uint8)
    out = img.copy()
    if kind == "scratch":
        p1 = rng.integers(int(s * .15), int(s * .85), 2)
        ang = rng.uniform(0, np.pi)
        length = rng.uniform(.2, .45) * s
        p2 = (p1 + length * np.array([np.cos(ang), np.sin(ang)])).astype(int).clip(0, s - 1)
        th = int(rng.integers(2, 4))
        cv2.line(mask, tuple(int(v) for v in p1), tuple(int(v) for v in p2), 1, th)
        out = np.where(mask > 0, out - rng.uniform(.18, .3), out)
    elif kind == "dent":
        c = rng.integers(int(s * .2), int(s * .8), 2)
        r = int(rng.uniform(.04, .08) * s)
        yy, xx = np.mgrid[0:s, 0:s]
        d = np.sqrt((yy - c[1]) ** 2 + (xx - c[0]) ** 2) / r
        shade = np.clip(1 - d, 0, 1)
        gx = (xx - c[0]) / max(r, 1)
        out = out + 0.22 * shade * gx * np.sign(rng.uniform(-1, 1))   # directional shading of a dent
        mask[d < 1] = 1
    elif kind == "stain":
        for _ in range(int(rng.integers(2, 5))):
            c = rng.integers(int(s * .2), int(s * .8), 2)
            axes = tuple(int(v) for v in rng.integers(int(s * .02), int(s * .06), 2))
            cv2.ellipse(mask, tuple(int(v) for v in c), axes, float(rng.uniform(0, 180)), 0, 360, 1, -1)
        blur = cv2.GaussianBlur(mask.astype(np.float32), (0, 0), 2)
        out = out + 0.15 * blur
    elif kind == "spot":                          # small dark pits
        for _ in range(int(rng.integers(1, 4))):
            c = rng.integers(int(s * .15), int(s * .85), 2)
            r = int(rng.integers(2, 6))
            cv2.circle(mask, tuple(int(v) for v in c), r, 1, -1)
        out = np.where(mask > 0, out - rng.uniform(.25, .4), out)
    elif kind == "geometric":                     # a sharp-edged foreign shape (burr / missing material)
        c = rng.integers(int(s * .25), int(s * .75), 2)
        w, h = (int(v) for v in rng.integers(int(s * .06), int(s * .14), 2))
        if rng.uniform() < 0.5:
            cv2.rectangle(mask, (int(c[0] - w // 2), int(c[1] - h // 2)), (int(c[0] + w // 2), int(c[1] + h // 2)), 1, -1)
        else:
            pts = np.array([[c[0], c[1] - h], [c[0] - w, c[1] + h // 2], [c[0] + w, c[1] + h // 2]], np.int32)
            cv2.fillPoly(mask, [pts], 1)
        out = np.where(mask > 0, rng.choice([.2, .9]), out)
    elif kind == "texture":                       # local change of brushing direction / roughness
        c = rng.integers(int(s * .25), int(s * .75), 2)
        r = int(rng.uniform(.08, .14) * s)
        cv2.circle(mask, tuple(int(v) for v in c), r, 1, -1)
        patch = rng.normal(0.0, 1.0, (s, s)).astype(np.float32)
        k = int(s * .12) | 1
        patch = cv2.GaussianBlur(patch, (1, k), 0)            # brushing rotated by 90 degrees
        patch = (patch - patch.mean()) / (patch.std() + 1e-6)
        out = np.where(mask > 0, out.mean() + 0.10 * patch, out)
    return np.clip(out, 0, 1), mask


def generate(root: Path, category: str = "brushed_metal", n_train: int = 40, n_test_good: int = 12,
             n_test_per_defect: int = 6, size: int = 256, seed: int = 0,
             kinds: tuple[str, ...] = DEFECT_KINDS) -> Path:
    """Render the synthetic dataset in MVTec-AD layout under ``root/category``."""
    rng = np.random.default_rng(seed)
    cat = root / category
    def save(img, rel):
        rgb = np.stack([img * .97, img, img * 1.02], -1)
        write_image(cat / rel, (np.clip(rgb, 0, 1) * 255).astype(np.uint8))
    for i in range(n_train):
        save(_texture(rng, size), f"train/good/{i:03d}.png")
    for i in range(n_test_good):
        save(_texture(rng, size), f"test/good/{i:03d}.png")
    for kind in kinds:
        for i in range(n_test_per_defect):
            img, m = _defect(rng, _texture(rng, size), kind)
            save(img, f"test/{kind}/{i:03d}.png")
            write_image(cat / f"ground_truth/{kind}/{i:03d}_mask.png", (m * 255).astype(np.uint8))
    (root / "SYNTHETIC_NOTICE.txt").write_text(NOTICE + "\n", encoding="utf-8")
    (root / "manifest.json").write_text(json.dumps(
        {"generator": "core.datasets.synthetic.generate", "seed": seed, "size": size, "kinds": list(kinds),
         "category": category, "label": LABEL, "notice": NOTICE}, indent=2), encoding="utf-8")
    return cat


def generate_pointclouds(root: Path, n_train: int = 4, n_test: int = 6, seed: int = 0) -> Path:
    """Synthetic 3D surface patches (height field z=f(x,y), units: arbitrary 'mm')."""
    rng = np.random.default_rng(seed)
    cat = root / "surface_patch_3d"
    for sub in ("train/good", "test/good", "test/bump", "test/dent", "ground_truth"):
        (cat / sub).mkdir(parents=True, exist_ok=True)

    def surface():
        n = 70
        x, y = np.meshgrid(np.linspace(-20, 20, n), np.linspace(-20, 20, n))
        z = 0.002 * (x ** 2 - y ** 2) + rng.normal(0, 0.02, x.shape)
        return x.ravel(), y.ravel(), z.ravel()

    for i in range(n_train):
        x, y, z = surface()
        np.savetxt(cat / f"train/good/{i:03d}.xyz", np.c_[x, y, z], fmt="%.5f")
    for i in range(n_test):
        x, y, z = surface()
        kind = ["good", "bump", "dent"][i % 3]
        lab = np.zeros_like(z)
        if kind != "good":
            cx, cy = rng.uniform(-10, 10, 2)
            d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2)
            prof = np.clip(1 - d / 4.0, 0, 1) ** 2
            z = z + (0.9 if kind == "bump" else -0.9) * prof
            lab = (prof > 0.05).astype(float)
        np.savetxt(cat / f"test/{kind}/{i:03d}.xyz", np.c_[x, y, z], fmt="%.5f")
        np.savetxt(cat / f"ground_truth/{i:03d}.txt", np.c_[x, y, z, lab], fmt="%.5f")
    return cat


class SyntheticAdapter(MVTecStyleAdapter):
    dataset_id = SYNTHETIC_ID
    folder_name = "synthetic_demo"
    synthetic = True
    modalities = ("rgb", "pointcloud")

    def list_categories(self, root: Path) -> list[str]:
        return [c for c in super().list_categories(root)]

    def index(self, root: Path, category: str) -> DatasetIndex:
        if category != "surface_patch_3d":
            idx = super().index(root, category)
            for s in idx.samples:
                s.meta["synthetic"] = True
            return idx
        cat = root / category
        samples = []
        for split in ("train", "test"):
            for cls_dir in sorted((cat / split).iterdir()):
                for f in sorted(cls_dir.glob("*.xyz")):
                    label = GOOD if cls_dir.name == "good" else BAD
                    gt = cat / "ground_truth" / f"{f.stem}.txt"
                    samples.append(Sample(
                        sample_id=f"{split}/{cls_dir.name}/{f.stem}", dataset_id=self.dataset_id,
                        category=category, split=split, label=label,
                        defect_type=None if label == GOOD else cls_dir.name,
                        modalities={"pointcloud": f},
                        masks={"pointcloud": gt} if (split == "test" and gt.exists()) else {},
                        meta={"synthetic": True, "units": "arbitrary (synthetic)"}))
        return DatasetIndex(self.dataset_id, category, root, samples)


def ensure_generated(data_root: Path) -> Path:
    root = data_root / SyntheticAdapter.folder_name
    if not (root / "brushed_metal").is_dir():
        generate(root)
    if not (root / "surface_patch_3d").is_dir():
        generate_pointclouds(root)
    return root
